#!/usr/bin/env node
/**
 * One-off: move every installed `deutsche-bahn` connector from the db-rest
 * schema to the MOTIS one shipped in v0.9.0.
 *
 * Prints SQL; does not connect to anything. Review it, then run it against
 * the cloud database:
 *
 *   node scripts/ops/migrate-deutsche-bahn-cloud.mjs http://motis:8080 > /tmp/db.sql
 *   scp /tmp/db.sql root@<droplet>:/tmp/db.sql
 *   ssh root@<droplet> 'docker exec -i amcp-cloud-postgres psql -U amcp -d anythingmcp -v ON_ERROR_STOP=1 -1 -f - < /tmp/db.sql'
 *   ssh root@<droplet> 'docker restart amcp-cloud-app'   # the tool registry is in memory
 *
 * Why not the catalog re-sync: the change is structural (every endpoint
 * moved) so the boot-time reconciler will not apply it, the per-connector
 * endpoint needs each owner to click, and the catalog's base URL is templated
 * ({{MOTIS_URL}}) so the diff never proposes a base-URL move. This does what a
 * `resync(id, 'full', { applyBaseUrl: true })` would, for all of them at once,
 * with the same rules: operator-written response mappings are kept, manual
 * disables are kept, tools the catalog dropped are soft-deprecated.
 *
 * A connector is recognised by `config.adapterSlug`, or — for installs that
 * predate the baseline — by the old public base URL.
 */
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..', '..');
const adapter = JSON.parse(
  readFileSync(join(ROOT, 'packages/backend/src/adapters/de/deutsche-bahn.json'), 'utf8'),
);

const motisUrl = (process.argv[2] || 'http://motis:8080').replace(/\/+$/, '');
const OLD_BASE = 'https://v6.db.transport.rest';

// Same fingerprinting as packages/backend/src/adapters/catalog-fingerprint.ts,
// so the stored adapterVersion matches what the running backend computes and
// the re-sync UI does not report a phantom update afterwards.
function canonicalize(v) {
  if (Array.isArray(v)) return v.map(canonicalize);
  if (v && typeof v === 'object') {
    const o = {};
    for (const k of Object.keys(v).sort()) o[k] = canonicalize(v[k]);
    return o;
  }
  return v;
}
const hashContent = (v) => createHash('sha256').update(JSON.stringify(canonicalize(v))).digest('hex').slice(0, 12);
const toolFingerprint = (t) => ({
  name: t.name,
  description: t.description ?? '',
  parameters: t.parameters ?? {},
  endpointMapping: t.endpointMapping ?? {},
  responseMapping: t.responseMapping ?? null,
  useProxy: t.useProxy === true,
});
const adapterVersion = hashContent({
  instructions: adapter.instructions ?? '',
  connector: {
    name: adapter.connector.name,
    type: adapter.connector.type,
    baseUrl: adapter.connector.baseUrl,
    authType: adapter.connector.authType,
  },
  tools: [...adapter.tools].map(toolFingerprint).sort((a, b) => a.name.localeCompare(b.name)),
});
const instructionsBaseline = hashContent({ instructions: adapter.instructions ?? '' });

const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;
const json = (v) => `${lit(JSON.stringify(v))}::jsonb`;

const out = [];
out.push('-- deutsche-bahn: db-rest → MOTIS. Generated by scripts/ops/migrate-deutsche-bahn-cloud.mjs');
out.push(`-- adapterVersion ${adapterVersion}, MOTIS at ${motisUrl}`);
out.push('CREATE TEMP TABLE db_targets AS');
out.push('  SELECT id FROM connectors');
out.push(`  WHERE config->>'adapterSlug' = 'deutsche-bahn' OR base_url LIKE ${lit(OLD_BASE + '%')};`);
out.push("SELECT count(*) AS connectors_to_migrate FROM db_targets;");

out.push('UPDATE connectors SET');
out.push(`  base_url = ${lit(motisUrl)},`);
out.push(`  headers = ${json(adapter.connector.headers)},`);
out.push(`  healthcheck_path = ${lit(adapter.connector.healthcheckPath)},`);
out.push(`  instructions = ${lit(adapter.instructions)},`);
out.push(`  env_vars = COALESCE(env_vars, '{}'::jsonb) || ${json({ MOTIS_URL: motisUrl })},`);
out.push(
  `  config = COALESCE(config, '{}'::jsonb) || ${json({
    adapterSlug: 'deutsche-bahn',
    adapterVersion,
    instructionsBaseline,
    baseUrlBaseline: motisUrl,
  })},`,
);
out.push('  updated_at = now()');
out.push('WHERE id IN (SELECT id FROM db_targets);');

for (const t of adapter.tools) {
  out.push(`-- ${t.name}`);
  out.push('UPDATE mcp_tools SET');
  out.push(`  description = ${lit(t.description)},`);
  out.push(`  parameters = ${json(t.parameters)},`);
  out.push(`  endpoint_mapping = ${json(t.endpointMapping)},`);
  // Only where nobody wrote one: same rule as the catalog re-sync. Three of
  // the 82 cloud connectors stored a JSON null rather than SQL NULL, which
  // COALESCE treats as a value — hence the explicit jsonb_typeof check.
  out.push(
    `  response_mapping = CASE WHEN response_mapping IS NULL OR jsonb_typeof(response_mapping) = 'null' THEN ${json(t.responseMapping)} ELSE response_mapping END,`,
  );
  out.push('  is_enabled = CASE WHEN deprecated_at IS NOT NULL THEN true ELSE is_enabled END,');
  out.push('  deprecated_at = NULL,');
  out.push('  updated_at = now()');
  out.push(`WHERE name = ${lit(t.name)} AND connector_id IN (SELECT id FROM db_targets);`);
}

const names = adapter.tools.map((t) => lit(t.name)).join(', ');
out.push('-- tools the catalog no longer ships (none expected; kept for symmetry with resync)');
out.push('UPDATE mcp_tools SET deprecated_at = now(), is_enabled = false, updated_at = now()');
out.push(`WHERE connector_id IN (SELECT id FROM db_targets) AND deprecated_at IS NULL AND name NOT IN (${names});`);

out.push("SELECT c.id, c.base_url, count(t.id) AS tools, count(t.response_mapping) AS mapped");
out.push('FROM connectors c JOIN mcp_tools t ON t.connector_id = c.id');
out.push('WHERE c.id IN (SELECT id FROM db_targets) GROUP BY c.id, c.base_url ORDER BY c.id LIMIT 200;');

process.stdout.write(out.join('\n') + '\n');
