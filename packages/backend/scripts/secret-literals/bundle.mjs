#!/usr/bin/env node
/**
 * Builds one self-contained JavaScript file from report.ts or repair.ts, to
 * run inside the cloud backend container even before an image containing
 * this code is deployed. Only `pg`, `crypto` and `@nestjs/common` are loaded
 * from the container (/app/backend/node_modules).
 *
 *   node scripts/secret-literals/bundle.mjs report   # prints the path of the bundle (a fresh temp dir)
 *   node scripts/secret-literals/bundle.mjs repair   # prints the path of the bundle (a fresh temp dir)
 *
 * Run it on the droplet (docker cp does not work there, see
 * reference_usage_analytics; the script travels in an environment variable):
 *
 *   B64=$(base64 < "$(node scripts/secret-literals/bundle.mjs report)" | tr -d '\n')
 *   ssh root@104.248.242.235 "docker exec -e SRC=$B64 amcp-cloud-backend \
 *     node -e \"eval(Buffer.from(process.env.SRC,'base64').toString())\""
 *
 * The repair is a dry run unless SECRET_REPAIR_ARGS contains --apply, e.g.
 *   docker exec -e SRC=… -e SECRET_REPAIR_ARGS="--apply --connector <id>" …
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const which = process.argv[2];
if (which !== 'report' && which !== 'repair') {
  console.error('usage: bundle.mjs report|repair');
  process.exit(2);
}

const backend = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const out = mkdtempSync(join(tmpdir(), 'secret-literals-'));
const tsc = resolve(backend, '..', '..', 'node_modules', '.bin', 'tsc');
execFileSync(
  tsc,
  [
    '--outDir', out,
    '--rootDir', backend,
    '--module', 'commonjs',
    '--target', 'ES2022',
    '--esModuleInterop',
    '--skipLibCheck',
    '--strictNullChecks',
    join(backend, 'scripts', 'secret-literals', `${which}.ts`),
  ],
  { stdio: 'inherit' },
);

const files = [];
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (p.endsWith('.js')) files.push(p);
  }
};
walk(out);

const entry = `scripts/secret-literals/${which}.js`;
const modules = files
  .map((file) => {
    const id = relative(out, file).split('\\').join('/');
    return `${JSON.stringify(id)}: function (module, exports, require) {\n${readFileSync(file, 'utf8')}\n}`;
  })
  .join(',\n');

const bundle = `// Generated by scripts/secret-literals/bundle.mjs (${which}). Do not edit.
(function () {
  const path = require('path');
  const external = require('module').createRequire(process.env.AMCP_BACKEND_DIR || '/app/backend/');
  if (process.env.SECRET_REPAIR_ARGS) process.argv.push(...process.env.SECRET_REPAIR_ARGS.split(/\\s+/).filter(Boolean));
  const defs = {\n${modules}\n};
  const cache = {};
  let main;
  function load(id) {
    if (cache[id]) return cache[id].exports;
    const module = { exports: {} };
    cache[id] = module;
    if (!main) main = module;
    const req = (spec) => {
      if (!spec.startsWith('.')) return external(spec);
      let target = path.posix.normalize(path.posix.join(path.posix.dirname(id), spec));
      if (!target.endsWith('.js')) target += '.js';
      if (!defs[target]) throw new Error('bundle: missing module ' + target);
      return load(target);
    };
    req.main = main;
    defs[id](module, module.exports, req);
    return module.exports;
  }
  load(${JSON.stringify(entry)});
})();
`;

const dir = mkdtempSync(join(tmpdir(), 'secret-literals-'));
const target = join(dir, `${which}.js`);
writeFileSync(target, bundle, { mode: 0o600 });
console.log(target);
