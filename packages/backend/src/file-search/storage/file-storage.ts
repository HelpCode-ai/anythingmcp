import { createReadStream } from 'node:fs';
import { mkdir, rm, stat, writeFile } from 'node:fs/promises';
import { dirname, join, resolve, sep } from 'node:path';
import type { Readable } from 'node:stream';
import { DeleteObjectCommand, GetObjectCommand, PutObjectCommand, S3Client } from '@aws-sdk/client-s3';
import { usesVirtualHostedBuckets } from '../file-search-config';

/**
 * Where File Share keeps the files behind its links (#1387).
 *
 *   FILES_STORAGE=local  (default) a directory, FILES_STORAGE_DIR (default
 *                        /data/files; a Docker volume on self-hosted installs)
 *   FILES_STORAGE=s3     an S3-compatible bucket: FILES_S3_ENDPOINT,
 *                        FILES_S3_REGION, FILES_S3_BUCKET,
 *                        FILES_S3_ACCESS_KEY_ID, FILES_S3_SECRET_ACCESS_KEY
 *                        (AnythingMCP Cloud: DigitalOcean Spaces, with a
 *                        lifecycle rule as a safety net behind the sweeper).
 *
 * Keys are generated by the server (`orgs/<orgId>/shares/<shareId>`), never
 * taken from a user.
 */
export interface FileStorage {
  readonly kind: 'local' | 's3';
  put(key: string, bytes: Buffer, contentType: string): Promise<void>;
  open(key: string): Promise<{ stream: Readable; size?: number }>;
  delete(key: string): Promise<void>;
}

const KEY_RE = /^[a-zA-Z0-9][a-zA-Z0-9/_.-]{0,400}$/;

function assertKey(key: string): void {
  if (!KEY_RE.test(key) || key.includes('..')) throw new Error('Invalid storage key');
}

export class LocalFileStorage implements FileStorage {
  readonly kind = 'local' as const;
  private readonly root: string;

  constructor(root: string) {
    this.root = resolve(root);
  }

  private pathOf(key: string): string {
    assertKey(key);
    const p = resolve(join(this.root, key));
    if (!p.startsWith(this.root + sep)) throw new Error('Invalid storage key');
    return p;
  }

  async put(key: string, bytes: Buffer): Promise<void> {
    const p = this.pathOf(key);
    await mkdir(dirname(p), { recursive: true, mode: 0o700 });
    await writeFile(p, bytes, { mode: 0o600 });
  }

  async open(key: string): Promise<{ stream: Readable; size?: number }> {
    const p = this.pathOf(key);
    const s = await stat(p);
    return { stream: createReadStream(p), size: s.size };
  }

  async delete(key: string): Promise<void> {
    await rm(this.pathOf(key), { force: true });
  }
}

export class S3FileStorage implements FileStorage {
  readonly kind = 's3' as const;
  private readonly client: S3Client;

  constructor(
    private readonly bucket: string,
    opts: { endpoint?: string; region?: string; accessKeyId: string; secretAccessKey: string },
  ) {
    this.client = new S3Client({
      endpoint: opts.endpoint || undefined,
      region: opts.region || 'us-east-1',
      forcePathStyle: !usesVirtualHostedBuckets(opts.endpoint),
      credentials: { accessKeyId: opts.accessKeyId, secretAccessKey: opts.secretAccessKey },
    });
  }

  async put(key: string, bytes: Buffer, contentType: string): Promise<void> {
    assertKey(key);
    await this.client.send(
      new PutObjectCommand({ Bucket: this.bucket, Key: key, Body: bytes, ContentType: contentType, ACL: 'private' }),
    );
  }

  async open(key: string): Promise<{ stream: Readable; size?: number }> {
    assertKey(key);
    const out = await this.client.send(new GetObjectCommand({ Bucket: this.bucket, Key: key }));
    return { stream: out.Body as Readable, size: out.ContentLength };
  }

  async delete(key: string): Promise<void> {
    assertKey(key);
    await this.client.send(new DeleteObjectCommand({ Bucket: this.bucket, Key: key }));
  }
}

export function fileStorageFromEnv(env: NodeJS.ProcessEnv = process.env): FileStorage {
  if ((env.FILES_STORAGE ?? 'local') === 's3') {
    const bucket = env.FILES_S3_BUCKET;
    const accessKeyId = env.FILES_S3_ACCESS_KEY_ID;
    const secretAccessKey = env.FILES_S3_SECRET_ACCESS_KEY;
    if (!bucket || !accessKeyId || !secretAccessKey) {
      throw new Error('FILES_STORAGE=s3 needs FILES_S3_BUCKET, FILES_S3_ACCESS_KEY_ID and FILES_S3_SECRET_ACCESS_KEY.');
    }
    return new S3FileStorage(bucket, { endpoint: env.FILES_S3_ENDPOINT, region: env.FILES_S3_REGION, accessKeyId, secretAccessKey });
  }
  return new LocalFileStorage(env.FILES_STORAGE_DIR || '/data/files');
}
