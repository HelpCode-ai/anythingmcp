// Shell completion scripts for amcp. All three scripts are generated from the
// FLAGS and COMMANDS tables below so a new command or flag reaches every shell.
// The scripts are static: they never read the config file or call a server.

export const SHELLS = ['bash', 'zsh', 'fish'] as const;
export type Shell = typeof SHELLS[number];

export interface FlagSpec { name: string; short?: string; value?: string; description: string }
interface Word { name: string; description: string }
export interface CommandSpec extends Word { flags?: string[]; subcommands?: CommandSpec[]; values?: Word[] }

// Every option accepted by parseArgs in index.ts; the CLI tests fail if the two differ.
export const FLAGS: readonly FlagSpec[] = [
  { name: 'url', value: 'instance URL', description: 'AnythingMCP instance base URL' },
  { name: 'server', value: 'server ID', description: 'MCP server ID' },
  { name: 'profile', value: 'profile name', description: 'Saved profile to use' },
  { name: 'key-stdin', description: 'Read the API key from stdin' },
  { name: 'filter', value: 'text', description: 'Show only tools whose name contains this text' },
  { name: 'args', value: 'JSON, @file.json or -', description: 'Tool arguments as a JSON object' },
  { name: 'yes', description: 'Run a destructive tool without asking' },
  { name: 'timeout', value: 'seconds', description: 'Tool call timeout in seconds' },
  { name: 'json', description: 'Machine-readable output' },
  { name: 'help', short: 'h', description: 'Show usage' },
];

const GLOBAL_FLAGS = ['json', 'help'];

export const COMMANDS: readonly CommandSpec[] = [
  { name: 'login', description: 'Verify an API key and save a profile', flags: ['url', 'server', 'key-stdin', 'profile'] },
  { name: 'logout', description: 'Remove a saved profile', flags: ['profile'] },
  { name: 'whoami', description: 'Show the saved profile', flags: ['profile'] },
  {
    name: 'tools', description: 'List, describe and call MCP tools', subcommands: [
      { name: 'ls', description: 'List tools', flags: ['filter', 'profile', 'url', 'server'] },
      { name: 'describe', description: 'Show a tool description and input schema', flags: ['profile', 'url', 'server'] },
      { name: 'call', description: 'Call a tool', flags: ['args', 'yes', 'timeout', 'profile', 'url', 'server'] },
    ],
  },
  {
    name: 'completion', description: 'Print a shell completion script',
    values: SHELLS.map((shell) => ({ name: shell, description: `${shell} completion script` })),
  },
];

export function isShell(value: string | undefined): value is Shell {
  return SHELLS.includes(value as Shell);
}

// A completion context is selected by the first two positionals, matched as the
// glob "<command>/<subcommand>". Each context offers words (positionals) and flags.
interface Context { pattern: string; words: readonly Word[]; flags: FlagSpec[] }

function flagsFor(names: string[] = []): FlagSpec[] {
  return [...names, ...GLOBAL_FLAGS].map((name) => {
    const flag = FLAGS.find((entry) => entry.name === name);
    if (!flag) throw new Error(`Unknown completion flag: ${name}`);
    return flag;
  });
}

function contexts(): Context[] {
  const list: Context[] = [{ pattern: '/', words: COMMANDS, flags: flagsFor() }];
  for (const command of COMMANDS) {
    if (command.subcommands) {
      list.push({ pattern: `${command.name}/`, words: command.subcommands, flags: flagsFor() });
      for (const sub of command.subcommands) {
        list.push({ pattern: `${command.name}/${sub.name}`, words: [], flags: flagsFor(sub.flags) });
      }
    } else if (command.values) {
      list.push({ pattern: `${command.name}/`, words: command.values, flags: flagsFor() });
    } else {
      list.push({ pattern: `${command.name}/*`, words: [], flags: flagsFor(command.flags) });
    }
  }
  return list;
}

const valueFlags = () => FLAGS.filter((flag) => flag.value);
const switches = (flag: FlagSpec) => [`--${flag.name}`, ...(flag.short ? [`-${flag.short}`] : [])];
const single = (text: string) => `'${text.replace(/'/g, `'\\''`)}'`;

function bashScript(): string {
  const values = valueFlags().map((flag) => `--${flag.name}`).join('|');
  const words = (flags: FlagSpec[]) => flags.flatMap(switches).join(' ');
  return [
    '# bash completion for amcp. Generated by `amcp completion bash`.',
    '_amcp() {',
    '  local cur=${COMP_WORDS[COMP_CWORD]} prev=${COMP_WORDS[COMP_CWORD-1]}',
    '  local cmd= sub= words= flags= i',
    `  case $prev in ${values}) return 0 ;; esac`,
    '  for ((i = 1; i < COMP_CWORD; i++)); do',
    '    case ${COMP_WORDS[i]} in',
    `      ${values}) ((i++)) ;;`,
    '      -*) ;;',
    '      *) if [[ -z $cmd ]]; then cmd=${COMP_WORDS[i]}; elif [[ -z $sub ]]; then sub=${COMP_WORDS[i]}; fi ;;',
    '    esac',
    '  done',
    '  case $cmd/$sub in',
    ...contexts().map((context) =>
      `    ${context.pattern}) words=${single(context.words.map((word) => word.name).join(' '))}; flags=${single(words(context.flags))} ;;`),
    `    *) flags=${single(words(flagsFor()))} ;;`,
    '  esac',
    '  if [[ $cur == -* || -z $words ]]; then words=$flags; fi',
    '  COMPREPLY=($(compgen -W "$words" -- "$cur"))',
    '}',
    'complete -F _amcp amcp',
    '',
  ].join('\n');
}

function zshScript(): string {
  const values = valueFlags().map((flag) => `--${flag.name}`).join('|');
  const described = (name: string, description: string) => single(`${name}:${description.replace(/:/g, '\\:')}`);
  const flagItems = (flags: FlagSpec[]) =>
    flags.flatMap((flag) => switches(flag).map((option) => described(option, flag.description))).join(' ');
  return [
    '#compdef amcp',
    '# zsh completion for amcp. Generated by `amcp completion zsh`.',
    '_amcp() {',
    '  local cmd= sub= i',
    '  local -a candidates options',
    '  case ${words[CURRENT-1]} in',
    ...valueFlags().map((flag) => `    --${flag.name}) _message ${single(flag.value!)}; return ;;`),
    '  esac',
    '  for ((i = 2; i < CURRENT; i++)); do',
    '    case ${words[i]} in',
    `      ${values}) ((i++)) ;;`,
    '      -*) ;;',
    '      *) if [[ -z $cmd ]]; then cmd=${words[i]}; elif [[ -z $sub ]]; then sub=${words[i]}; fi ;;',
    '    esac',
    '  done',
    '  case $cmd/$sub in',
    ...contexts().map((context) =>
      `    ${context.pattern}) candidates=(${context.words.map((word) => described(word.name, word.description)).join(' ')}); options=(${flagItems(context.flags)}) ;;`),
    `    *) options=(${flagItems(flagsFor())}) ;;`,
    '  esac',
    '  if [[ $PREFIX == -* || ${#candidates} -eq 0 ]]; then',
    '    _describe -t options option options',
    '  else',
    '    _describe -t commands command candidates',
    '  fi',
    '}',
    'if [[ ${zsh_eval_context[-1]} == loadautofunc ]]; then _amcp "$@"; else compdef _amcp amcp; fi',
    '',
  ].join('\n');
}

function fishScript(): string {
  const values = valueFlags().map((flag) => `--${flag.name}`).join(' ');
  const when = (pattern: string) => single(`string match -q -- "${pattern}" (__amcp_context)`);
  const lines = [
    '# fish completion for amcp. Generated by `amcp completion fish`.',
    'function __amcp_context',
    '    set -l cmd',
    '    set -l sub',
    '    set -l skip 0',
    '    for token in (commandline -opc)[2..-1]',
    '        if test $skip -eq 1',
    '            set skip 0',
    '            continue',
    '        end',
    '        switch $token',
    `            case ${values}`,
    '                set skip 1',
    "            case '-*'",
    "            case '*'",
    '                if test -z "$cmd"',
    '                    set cmd $token',
    '                else if test -z "$sub"',
    '                    set sub $token',
    '                end',
    '        end',
    '    end',
    '    echo "$cmd/$sub"',
    'end',
    '',
    'complete -c amcp -f',
  ];
  const flagLine = (flag: FlagSpec, condition = '') => ['complete -c amcp', condition,
    flag.short ? `-s ${flag.short}` : '', `-l ${flag.name}`, flag.value ? '-r' : '',
    `-d ${single(flag.description)}`].filter(Boolean).join(' ');
  for (const flag of flagsFor()) lines.push(flagLine(flag));
  for (const context of contexts()) {
    for (const word of context.words) {
      lines.push(`complete -c amcp -n ${when(context.pattern)} -a ${single(word.name)} -d ${single(word.description)}`);
    }
    for (const flag of context.flags) {
      if (!GLOBAL_FLAGS.includes(flag.name)) lines.push(flagLine(flag, `-n ${when(context.pattern)}`));
    }
  }
  return lines.join('\n') + '\n';
}

export function completionScript(shell: Shell): string {
  if (shell === 'bash') return bashScript();
  if (shell === 'zsh') return zshScript();
  return fishScript();
}
